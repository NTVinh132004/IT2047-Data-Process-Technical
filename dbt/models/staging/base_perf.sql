    NULLIF(TRIM(mi_cancellation_flag), '') AS mi_cancellation_flag,
    NULLIF(TRIM(servicer_name), '') AS servicer_name,
    CAST(NULLIF(TRIM(bankruptcy_cramdown_costs), '') AS DECIMAL(20, 4)) AS bankruptcy_cramdown_costs,
    load_date,
    record_source,
    source_file,
    period
