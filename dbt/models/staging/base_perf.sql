    CAST(NULLIF(TRIM(maintenance_costs), '') AS DECIMAL(20, 4)) AS maintenance_costs,
    CAST(NULLIF(TRIM(taxes_insurance), '') AS DECIMAL(20, 4)) AS taxes_insurance,
    CAST(NULLIF(TRIM(misc_expenses), '') AS DECIMAL(20, 4)) AS misc_expenses,
    CAST(NULLIF(TRIM(actual_loss), '') AS DECIMAL(20, 4)) AS actual_loss,
    CAST(NULLIF(TRIM(cumulative_modification_cost), '') AS DECIMAL(20, 4)) AS cumulative_modification_cost,
    NULLIF(TRIM(interest_rate_step_flag), '') AS interest_rate_step_flag,
    NULLIF(TRIM(payment_deferral_flag), '') AS payment_deferral_flag,
