    CAST(NULLIF(TRIM(non_interest_bearing_upb), '') AS DECIMAL(20, 4)) AS non_interest_bearing_upb,
    NULLIF(TRIM(ddlpi), '') AS ddlpi,
    CAST(NULLIF(TRIM(mi_recoveries), '') AS DECIMAL(20, 4)) AS mi_recoveries,
    CAST(NULLIF(TRIM(net_sales_proceeds), '') AS DECIMAL(20, 4)) AS net_sales_proceeds,
    CAST(NULLIF(TRIM(non_mi_recoveries), '') AS DECIMAL(20, 4)) AS non_mi_recoveries,
