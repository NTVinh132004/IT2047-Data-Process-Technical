    NULLIF(TRIM(loan_id), '') AS loan_id,
    NULLIF(TRIM(reporting_period), '') AS reporting_period,
    CAST(NULLIF(TRIM(current_upb), '') AS DECIMAL(20, 4)) AS current_upb,
    NULLIF(TRIM(delinquency_status), '') AS delinquency_status,
    CAST(NULLIF(TRIM(loan_age), '') AS INT) AS loan_age,
    CAST(NULLIF(TRIM(remaining_months), '') AS INT) AS remaining_months,
