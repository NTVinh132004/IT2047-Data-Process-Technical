-- Sinh tự động bằng scripts/gen_dbt_staging.py từ conf/schema/orig.yml, đừng sửa tay.
-- Ép kiểu, chuỗi rỗng thành null; giữ nguyên mã thiếu (DV-02). Đã qua cổng chất lượng nên ép kiểu không lỗi.
SELECT
    CAST(NULLIF(TRIM(credit_score), '') AS INT) AS credit_score,
    NULLIF(TRIM(first_payment_date), '') AS first_payment_date,
    NULLIF(TRIM(first_time_homebuyer_flag), '') AS first_time_homebuyer_flag,
    NULLIF(TRIM(maturity_date), '') AS maturity_date,
    NULLIF(TRIM(msa_code), '') AS msa_code,
    CAST(NULLIF(TRIM(mi_pct), '') AS INT) AS mi_pct,
    CAST(NULLIF(TRIM(number_of_units), '') AS INT) AS number_of_units,
    NULLIF(TRIM(occupancy_status), '') AS occupancy_status,
    CAST(NULLIF(TRIM(orig_cltv), '') AS INT) AS orig_cltv,
    CAST(NULLIF(TRIM(orig_dti), '') AS INT) AS orig_dti,
    CAST(NULLIF(TRIM(orig_upb), '') AS DECIMAL(20, 4)) AS orig_upb,
    CAST(NULLIF(TRIM(orig_ltv), '') AS INT) AS orig_ltv,
    CAST(NULLIF(TRIM(orig_interest_rate), '') AS DECIMAL(20, 4)) AS orig_interest_rate,
    NULLIF(TRIM(channel), '') AS channel,
    NULLIF(TRIM(prepayment_penalty_flag), '') AS prepayment_penalty_flag,
    NULLIF(TRIM(amortization_type), '') AS amortization_type,
    NULLIF(TRIM(property_state), '') AS property_state,
    NULLIF(TRIM(property_type), '') AS property_type,
    NULLIF(TRIM(postal_code), '') AS postal_code,
    NULLIF(TRIM(loan_id), '') AS loan_id,
    NULLIF(TRIM(loan_purpose), '') AS loan_purpose,
    CAST(NULLIF(TRIM(orig_loan_term), '') AS INT) AS orig_loan_term,
    CAST(NULLIF(TRIM(number_of_borrowers), '') AS INT) AS number_of_borrowers,
    NULLIF(TRIM(seller_name), '') AS seller_name,
    NULLIF(TRIM(super_conforming_flag), '') AS super_conforming_flag,
    NULLIF(TRIM(pre_harp_loan_id), '') AS pre_harp_loan_id,
    NULLIF(TRIM(special_eligibility_program), '') AS special_eligibility_program,
    NULLIF(TRIM(harp_indicator), '') AS harp_indicator,
    NULLIF(TRIM(property_valuation_method), '') AS property_valuation_method,
    NULLIF(TRIM(interest_only_flag), '') AS interest_only_flag,
    CAST(NULLIF(TRIM(vantage_score_4), '') AS INT) AS vantage_score_4,
    load_date,
    record_source,
    source_file,
    period
FROM {{ source('quality', 'orig_clean') }}
